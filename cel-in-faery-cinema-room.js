      var holdG = at(-(W / 2 - 0.06), 0, RAIL[0], LEFT);
      kit.hold(kit.facets(new T.CylinderGeometry(0.19, 0.19, 0.05, 22), M(holdG, at(1.55, 0.94, 0.2)), '--rdr-brass'), { say: 'a film can' });
